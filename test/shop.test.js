'use strict';
const { test } = require('node:test');
const assert = require('node:assert');
const path = require('node:path');
const os = require('node:os');
const fs = require('node:fs');
const shop = require('../shared/shop');

test('shared/shop defines categories and default equipped mapping', () => {
  assert.deepStrictEqual(shop.SHOP_CATEGORIES, ['wing', 'finish', 'trail', 'firework', 'voice', 'visor']);
  assert.strictEqual(typeof shop.DEFAULT_EQUIPPED, 'object');
  for (const cat of shop.SHOP_CATEGORIES) {
    const defId = shop.DEFAULT_EQUIPPED[cat];
    assert.ok(defId, `default for ${cat} exists`);
    const item = shop.itemById(defId);
    assert.ok(item, `default item ${defId} exists in catalog`);
    assert.strictEqual(item.category, cat);
    assert.strictEqual(item.price, 0, 'defaults must be free (0 CR)');
    assert.strictEqual(shop.isDefaultItem(defId), true);
  }
});

test('shared/shop catalogs all items with valid procedural params', () => {
  assert.ok(shop.SHOP_ITEMS.length >= 26);
  for (const item of shop.SHOP_ITEMS) {
    assert.ok(item.id, 'item has id');
    assert.ok(shop.SHOP_CATEGORIES.includes(item.category), `valid category for ${item.id}`);
    assert.strictEqual(typeof item.name, 'string');
    assert.strictEqual(typeof item.desc, 'string');
    assert.strictEqual(typeof item.price, 'number');
    assert.ok(item.price >= 0);
    assert.strictEqual(typeof item.params, 'object', `procedural params on ${item.id}`);
  }
});

test('shared/shop defines round sponsors with cost and effect', () => {
  assert.strictEqual(shop.ROUND_SPONSORS.length, 3);
  for (const sp of shop.ROUND_SPONSORS) {
    assert.ok(sp.id.startsWith('sponsor_'));
    assert.ok(sp.cost > 0);
    assert.strictEqual(typeof sp.effect, 'string');
    assert.strictEqual(shop.sponsorById(sp.id), sp);
  }
});

test('shared/shop toEsModuleSource renders importable browser module', async () => {
  const src = shop.toEsModuleSource();
  assert.ok(src.startsWith('// Generated by the server'));
  assert.ok(src.includes('export const SHOP_ITEMS'));
  assert.ok(src.includes('export const ROUND_SPONSORS'));
  const tmp = path.join(os.tmpdir(), `shop-esm-${process.pid}.mjs`);
  fs.writeFileSync(tmp, src);
  const mod = await import(tmp);
  assert.strictEqual(mod.SHOP_CATEGORIES.length, 6);
  assert.strictEqual(typeof mod.itemById, 'function');
  assert.strictEqual(typeof mod.itemsByCategory, 'function');
  assert.strictEqual(typeof mod.sponsorById, 'function');
  assert.strictEqual(typeof mod.isDefaultItem, 'function');
  fs.unlinkSync(tmp);
});
