'use strict';
const { test } = require('node:test');
const assert = require('node:assert');
const path = require('node:path');
const os = require('node:os');
const fs = require('node:fs');
const shop = require('../shared/shop');

test('shared/shop defines categories and default equipped mapping', () => {
  assert.deepStrictEqual(shop.SHOP_CATEGORIES, ['wing', 'finish', 'canopy', 'trail', 'firework', 'voice', 'visor']);
  assert.strictEqual(typeof shop.DEFAULT_EQUIPPED, 'object');
  for (const cat of shop.SHOP_CATEGORIES) {
    const defId = shop.DEFAULT_EQUIPPED[cat];
    assert.ok(defId, `default for ${cat} exists`);
    const item = shop.itemById(defId);
    assert.ok(item, `default item ${defId} exists in catalog`);
    assert.strictEqual(item.category, cat);
    assert.strictEqual(item.price, 0, 'defaults must be free (0 CR)');
    assert.strictEqual(shop.isDefaultItem(defId), true);
  }
});

test('shared/shop catalogs all items with valid procedural params', () => {
  assert.ok(shop.SHOP_ITEMS.length >= 26);
  for (const item of shop.SHOP_ITEMS) {
    assert.ok(item.id, 'item has id');
    assert.ok(shop.SHOP_CATEGORIES.includes(item.category), `valid category for ${item.id}`);
    assert.strictEqual(typeof item.name, 'string');
    assert.strictEqual(typeof item.desc, 'string');
    assert.strictEqual(typeof item.price, 'number');
    assert.ok(item.price >= 0);
    assert.strictEqual(typeof item.params, 'object', `procedural params on ${item.id}`);
  }
});

test('shared/shop defines round sponsors with cost and effect', () => {
  assert.strictEqual(shop.ROUND_SPONSORS.length, 3);
  for (const sp of shop.ROUND_SPONSORS) {
    assert.ok(sp.id.startsWith('sponsor_'));
    assert.ok(sp.cost > 0);
    assert.strictEqual(typeof sp.effect, 'string');
    assert.strictEqual(shop.sponsorById(sp.id), sp);
  }
});

test('shared/shop toEsModuleSource renders importable browser module', async () => {
  const src = shop.toEsModuleSource();
  assert.ok(src.startsWith('// Generated by the server'));
  assert.ok(src.includes('export const SHOP_ITEMS'));
  assert.ok(src.includes('export const ROUND_SPONSORS'));
  const tmp = path.join(os.tmpdir(), `shop-esm-${process.pid}.mjs`);
  fs.writeFileSync(tmp, src);
  const mod = await import(tmp);
  assert.strictEqual(mod.SHOP_CATEGORIES.length, 7);
  assert.strictEqual(typeof mod.itemById, 'function');
  assert.strictEqual(typeof mod.itemsByCategory, 'function');
  assert.strictEqual(typeof mod.sponsorById, 'function');
  assert.strictEqual(typeof mod.isDefaultItem, 'function');
  fs.unlinkSync(tmp);
});

test('procedural cosmetics catalog covers all cosmetic styles across 7 categories including canopy', () => {
  const expectedKits = {
    wing: ['wing_default', 'wing_xwing', 'wing_triplane', 'wing_twinboom', 'wing_saucer'],
    finish: ['finish_default', 'finish_chrome', 'finish_synth', 'finish_holo', 'finish_gold'],
    canopy: ['canopy_default', 'canopy_amber', 'canopy_stealth', 'canopy_bubble', 'canopy_cage', 'canopy_holo'],
    trail: ['trail_default', 'trail_voxel', 'trail_rings', 'trail_rainbow', 'trail_lightning'],
    firework: ['fw_default', 'fw_saturn', 'fw_spiral', 'fw_hearts'],
    voice: ['voice_default', 'voice_chiptune', 'voice_dreadnought', 'voice_sonar'],
    visor: ['visor_default', 'visor_shades', 'visor_led', 'visor_laurel'],
  };

  for (const [cat, itemIds] of Object.entries(expectedKits)) {
    for (const id of itemIds) {
      const item = shop.itemById(id);
      assert.ok(item, `Item ${id} must exist in shop catalog`);
      assert.strictEqual(item.category, cat);
      assert.strictEqual(typeof item.params, 'object', `${id} must specify procedural params`);
    }
  }

  // Check specific required procedural params
  const chrome = shop.itemById('finish_chrome');
  assert.strictEqual(chrome.params.metalness, 0.95);
  assert.strictEqual(chrome.params.roughness, 0.08);

  const gold = shop.itemById('finish_gold');
  assert.strictEqual(gold.params.metalness, 0.9);
  assert.strictEqual(gold.params.roughness, 0.2);

  const holo = shop.itemById('finish_holo');
  assert.strictEqual(holo.params.transparent, true);
  assert.strictEqual(holo.params.opacity, 0.72);

  const amber = shop.itemById('canopy_amber');
  assert.strictEqual(amber.params.tint, 0xffb326);
  assert.strictEqual(amber.params.metallic, true);

  const stealth = shop.itemById('canopy_stealth');
  assert.strictEqual(stealth.params.faceted, true);

  const bubble = shop.itemById('canopy_bubble');
  assert.strictEqual(bubble.params.panoramic, true);

  const cage = shop.itemById('canopy_cage');
  assert.strictEqual(cage.params.ribs, 3);

  const holoCanopy = shop.itemById('canopy_holo');
  assert.strictEqual(holoCanopy.params.reticle, true);
});
